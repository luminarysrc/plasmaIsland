#!/usr/bin/env python3
"""Turn po/*.po into package/contents/ui/Translations.js.

Plasma picks one UI language for the whole shell, so a per-widget language choice can't use
the .mo files. This dictionary lets the widget translate its own strings (see Translator.qml).
Keys are "msgid" or "msgctxt\\x04msgid"; untranslated and fuzzy entries are skipped.
"""
import ast
import glob
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def parse_po(path):
    entries = {}
    ctx = msgid = msgstr = None
    field = None
    fuzzy = False
    pending_fuzzy = False

    def flush():
        nonlocal ctx, msgid, msgstr, field, fuzzy
        if msgid and msgstr and not fuzzy:
            entries[(ctx + "\x04" if ctx else "") + msgid] = msgstr
        ctx = msgid = msgstr = field = None
        fuzzy = False

    with open(path, encoding="utf-8") as f:
        for raw in f:
            line = raw.strip()
            if line.startswith("#,") and "fuzzy" in line:
                pending_fuzzy = True
                continue
            if line.startswith("#") or not line:
                if not line:
                    flush()
                    pending_fuzzy = False
                continue
            m = re.match(r"(msgctxt|msgid_plural|msgid|msgstr(?:\[\d+\])?)\s+(\".*\")$", line)
            if m:
                key, val = m.group(1), ast.literal_eval(m.group(2))
                if key == "msgctxt":
                    if msgid is not None:
                        flush()
                    ctx, field = val, "ctx"
                    fuzzy = pending_fuzzy
                elif key == "msgid":
                    if msgid is not None:
                        flush()
                    msgid, field = val, "id"
                    fuzzy = fuzzy or pending_fuzzy
                elif key == "msgid_plural":
                    field = "plural"
                elif key == "msgstr":
                    msgstr, field = val, "str"
                else:  # msgstr[n]: plurals aren't used by this widget
                    field = "plural"
            elif line.startswith('"') and field:
                val = ast.literal_eval(line)
                if field == "ctx":
                    ctx += val
                elif field == "id":
                    msgid += val
                elif field == "str":
                    msgstr += val
    flush()
    return entries


def main():
    langs = {}
    for po in sorted(glob.glob(os.path.join(ROOT, "po", "*.po"))):
        langs[os.path.basename(po)[:-3]] = parse_po(po)
    out = os.path.join(ROOT, "package", "contents", "ui", "Translations.js")
    with open(out, "w", encoding="utf-8") as f:
        f.write("// GENERATED by po/gen-js.py from po/*.po (run po/build.sh). Do not edit.\n")
        f.write(".pragma library\n\n")
        f.write("var dict = " + json.dumps(langs, ensure_ascii=False, indent=1, sort_keys=True) + ";\n\n")
        f.write('''// lang: "" is handled by the caller (system i18n); "en" or an unknown code returns the msgid.
function tr(lang, ctx, msgid, args) {
    var table = dict[lang];
    var key = ctx ? ctx + "\\u0004" + msgid : msgid;
    var s = (table && table[key]) || msgid;
    return s.replace(/%(\\d+)/g, function (m, n) {
        return args[n - 1] !== undefined ? String(args[n - 1]) : m;
    });
}
''')


main()
